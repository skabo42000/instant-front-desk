// A real SDK client and child-process stdio session; all data/models are fictional.
import assert from 'node:assert/strict';
import { Client } from '@modelcontextprotocol/client';
import { StdioClientTransport } from '@modelcontextprotocol/client/stdio';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('..', import.meta.url));
const fixture = JSON.parse(await readFile(new URL('../tests/fixtures/mcp-maple-street-dental.json', import.meta.url), 'utf8'));
export async function fictionalStdioSession({ writeTranscript = false } = {}) {
  const env = Object.fromEntries(['PATH', 'SystemRoot', 'TMPDIR', 'TMP', 'TEMP'].flatMap(key => process.env[key] ? [[key, process.env[key]]] : []));
  const transport = new StdioClientTransport({ command: process.execPath,
    args: ['--conditions=react-server', path.join(root, 'scripts/run-mcp-fictional.cjs')], cwd: root, env, stderr: 'pipe' });
  const client = new Client({ name: 'ifd-fictional-portfolio-check', version: '0.1.0' });
  transport.stderr?.resume();
  const exchanges = [];
  let childPid;
  let result;
  try {
    await client.connect(transport);
    childPid = transport.pid;
    const tools = (await client.listTools()).tools.map(tool => tool.name).sort();
    assert.deepEqual(tools, ['ask_business', 'get_business', 'get_evaluation_report', 'list_businesses']);
    async function call(name, args, error = false) {
      const reply = await client.callTool({ name, arguments: args });
      assert.equal(!!reply.isError, error, `${name}: unexpected error state`);
      const output = error ? { isError: true } : reply.structuredContent;
      assert.ok(output);
      exchanges.push({ tool: name, input: args, output });
      return output;
    }
    const businessId = fixture.business.businessId;
    const listed = await call('list_businesses', {});
    assert.deepEqual(listed.businesses, [fixture.business]);
    const business = await call('get_business', { businessId });
    assert.equal(business.business.chunkCount, 1);
    const report = await call('get_evaluation_report', { businessId });
    assert.deepEqual([report.report.total, report.report.passed, report.report.failed, report.report.errors], [3, 1, 2, 1]);
    const cited = await call('ask_business', { businessId, question: 'What are the Saturday hours?' });
    assert.equal(cited.kind, 'answer');
    assert.equal(cited.text, 'Saturday hours are 9 am to noon. Appointments required.');
    assert.deepEqual(cited.citations, [{ id: '00000000-0000-0000-0000-000000000501', pageUrl: fixture.business.sourceUrl, heading: 'Fictional example' }]);
    const refusal = await call('ask_business', { businessId, question: 'What is the exact price of a checkup?' });
    assert.equal(refusal.kind, 'refusal');
    assert.match(refusal.text, /couldn't find/);
    assert.deepEqual(refusal.citations, []);
    await call('ask_business', { businessId, question: '' }, true);
    // This is captured SDK evidence, never a hand-authored imitation of protocol results.
    result = { fictional: true, transport: 'official SDK -> child stdio -> HMAC API (in-process HTTP transport; no listener)', tools,
      exchanges, liveModelCalls: 0, agentDemonstration: false };
  } finally {
    await client.close();
    await transport.close();
  }
  assert.ok(childPid, 'Missing stdio child PID');
  // Do not claim cleanup just because close() returned: check the child is gone.
  let alive = false;
  try { process.kill(childPid, 0); alive = true; } catch (error) { assert.equal(error.code, 'ESRCH'); }
  assert.equal(alive, false, 'Stdio child still running');
  result.processesStopped = true;
  if (writeTranscript) {
    const markdown = '# Fictional MCP stdio transcript\n\nGenerated by `npm run mcp:demo` from an actual SDK session.\n' +
      'Maple Street Dental and its saved evaluation are invented. Responses use FakeModel and FakeEmbeddings.\n' +
      'Zero live provider calls; scripted protocol evidence, not an assistant choosing tools or measured model quality.\n\n' +
      '```json\n' + JSON.stringify(result, null, 2) + '\n```\n';
    await writeFile(path.join(root, 'docs/mcp-demo-transcript.md'), markdown);
  }
  return result;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  fictionalStdioSession({ writeTranscript: process.argv.includes('--write-transcript') })
    .then(result => console.log(JSON.stringify(result, null, 2)))
    .catch(() => { console.error('Fictional stdio check failed; no private details logged.'); process.exitCode = 1; });
}
